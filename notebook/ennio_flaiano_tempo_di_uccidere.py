def clean_text_for_sentiment(text):
    """Clean text for sentiment analysis while preserving sentiment-carrying elements"""
    if pd.isna(text):
        return ""

    text = str(text).strip()

    # Basic cleaning while preserving sentiment
    text = text.replace('\n', ' ').replace('\t', ' ')

    # Remove excessive whitespace
    import re
    text = re.sub(r'\s+', ' ', text)

    # Remove empty parentheses, brackets, but keep content
    text = re.sub(r'\(\s*\)', '', text)
