def analyze_sentiment_feelit(texts, classifier):
    """Analyze sentiment using FEEL-IT with detailed progress tracking"""
    results = []

    print(f"Analyzing {len(texts)} segments with FEEL-IT...")

    # Process in smaller batches to manage memory and show progress
    batch_size = 20  # Smaller batches for better progress tracking
    total_batches = (len(texts) + batch_size - 1) // batch_size

    for batch_idx in range(0, len(texts), batch_size):
        batch_end = min(batch_idx + batch_size, len(texts))
        batch = texts[batch_idx:batch_end]

        # Prepare texts (truncate to model limit)
        batch_texts = []
        for text in batch:
            # FEEL-IT works best with segments up to 512 tokens
            if len(text) > 400:  # Conservative limit
                text = text[:400] + "..."
            batch_texts.append(text)

        try:
            # Get sentiment predictions
            predictions = classifier(batch_texts)

            # Process results - handle different possible outputs
            for i, pred in enumerate(predictions):
                original_text = batch[i]

                # FEEL-IT might return different formats
                if isinstance(pred, dict):
                    # Standard format: {'label': 'POSITIVE', 'score': 0.85}
                    label = pred.get('label', 'NEUTRAL')
                    confidence = pred.get('score', 0.5)
                elif isinstance(pred, list):
                    # List format: [{'label': 'POSITIVE', 'score': 0.85}]
                    if len(pred) > 0:
                        label = pred[0].get('label', 'NEUTRAL')
                        confidence = pred[0].get('score', 0.5)
                    else:
                        label = 'NEUTRAL'
                        confidence = 0.5
                else:
                    # Fallback
                    label = 'NEUTRAL'
                    confidence = 0.5

                results.append({
                    'text': original_text,
                    'sentiment_label': label,
                    'sentiment_confidence': confidence,
                    'text_length': len(original_text)
                })

        except Exception as e:
            print(f"⚠️ Error in batch {batch_idx//batch_size + 1}: {e}")

            # Add neutral values for failed batch
            for text in batch:
                results.append({
                    'text': text,
                    'sentiment_label': 'NEUTRAL',
                    'sentiment_confidence': 0.5,
                    'text_length': len(text)
                })

        # Progress update
        current_batch = batch_idx // batch_size + 1
        print(f"✓ Processed batch {current_batch}/{total_batches} ({batch_end}/{len(texts)} segments)")

    return results

